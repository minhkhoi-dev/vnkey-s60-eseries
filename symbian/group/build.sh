#!/usr/bin/env bash
# Builds and self-signs vnkey.sisx with GnuPoc on Linux (in the SDK's Docker image, see
# docker-build.sh). Requires: EPOCROOT (with trailing slash), SDK tools on PATH, openssl.
# Every run bumps the build number in ../VERSION (major.minor.build) and regenerates
# ../inc/VnKeyVersion.h, so each sisx is told apart on the phone and in the log.
set -euo pipefail
: "${EPOCROOT:?Set EPOCROOT to your GnuPoc S60 3rd FP2 SDK root, with trailing slash}"

cd "$(dirname "$0")"

# Symbian limits: major 0-127, minor 0-99, build 0-32767.
[ -f ../VERSION ] || { echo "build.sh: ../VERSION is missing (expected e.g. 0.0.0)" >&2; exit 1; }
IFS=. read -r V_MAJOR V_MINOR V_BUILD EXTRA < <(tr -d '\r' < ../VERSION | head -n 1) || true
re='^[0-9]+$'
if [[ ! $V_MAJOR =~ $re || ! $V_MINOR =~ $re || ! $V_BUILD =~ $re || -n "${EXTRA:-}" ]]; then
    echo "build.sh: ../VERSION must be three integers, major.minor.build" >&2
    exit 1
fi
V_BUILD=$((10#$V_BUILD + 1))
V_MAJOR=$((10#$V_MAJOR))
V_MINOR=$((10#$V_MINOR))
if [ "$V_MAJOR" -gt 127 ] || [ "$V_MINOR" -gt 99 ] || [ "$V_BUILD" -gt 32767 ]; then
    echo "build.sh: version $V_MAJOR.$V_MINOR.$V_BUILD out of range (127.99.32767)" >&2
    exit 1
fi
VERSION="$V_MAJOR.$V_MINOR.$V_BUILD"

# Where Options > Send log goes first: the web stub on the machine that builds
# (docker-build.sh passes its LAN address); the phone's query lets it be changed.
LOG_SERVER="${VNKEY_LOG_SERVER:-192.168.1.10:8060}"
if [[ ! $LOG_SERVER =~ ^[0-9A-Za-z.-]+:[0-9]+$ ]] || [ ${#LOG_SERVER} -gt 60 ]; then
    echo "build.sh: VNKEY_LOG_SERVER must be address:port, at most 60 characters: '$LOG_SERVER'" >&2
    exit 1
fi

printf '%s\n' "$VERSION" > ../VERSION
cat > ../inc/VnKeyVersion.h <<EOV
// Generated by group/build.sh from ../VERSION - do not edit.
#ifndef VNKEYVERSION_H
#define VNKEYVERSION_H
#include <e32std.h>
_LIT(KVnVersion, "$VERSION");
_LIT(KVnLogServer, "$LOG_SERVER");
#endif // VNKEYVERSION_H
EOV

bldmake bldfiles
abld build gcce urel
# abld reports success even when a file does not compile
for bin in vnkey.exe vnkeyfep.dll vnkeyboot.exe; do
    path="${EPOCROOT}epoc32/release/gcce/urel/$bin"
    if [ ! -f "$path" ] || [ "$path" -ot ../src/VnCatcher.cpp ] || [ "$path" -ot ../src/VnShared.cpp ] \
       || [ "$path" -ot ../src/VnKeyBoot.cpp ]; then
        echo "build.sh: $path was not built, see the errors above" >&2
        exit 1
    fi
done

# The icon: gfx/vnkey.svg as it is into a MIF. GnuPoc's own mifconv puts the SVG text in
# (no svgtbinencode, a Windows tool); the phone's SVG engine reads SVG text as well.
mifconv "${EPOCROOT}epoc32/data/z/resource/apps/vnkey_aif.mif" ../gfx/vnkey.svg
# abld goes on when a resource file does not compile either
for res in vnkey.rsc vnkey_en.rsc vnkey_aif.mif; do
    path="${EPOCROOT}epoc32/data/z/resource/apps/$res"
    if [ ! -f "$path" ] || [ "$path" -ot ../data/vnkey.rss ]; then
        echo "build.sh: $path was not made, see the errors above" >&2
        exit 1
    fi
done

cd ../sis
sed -e "s#\$(EPOCROOT)#${EPOCROOT}#g" \
    -e "s#@VERSION_MAJOR@#${V_MAJOR}#g" \
    -e "s#@VERSION_MINOR@#${V_MINOR}#g" \
    -e "s#@VERSION_BUILD@#${V_BUILD}#g" \
    vnkey.pkg > build.pkg

if [ ! -f dev.key ]; then
    # Old signsis wants SHA1 + a traditional "BEGIN RSA PRIVATE KEY" PEM.
    openssl req -new -x509 -sha1 -newkey rsa:1024 -nodes -days 3650 \
        -subj "/CN=VnKey Dev" -keyout dev.key -out dev.cer
    openssl rsa -in dev.key -out dev.key -traditional 2>/dev/null || true
fi

grep '^#{"VnKey"}' build.pkg
makesis build.pkg vnkey_unsigned.sis
signsis vnkey_unsigned.sis vnkey.sisx dev.cer dev.key
echo "Built $(pwd)/vnkey.sisx (version $VERSION, log server $LOG_SERVER)"
